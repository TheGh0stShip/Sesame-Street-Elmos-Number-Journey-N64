#!/usr/bin/env python3
"""mkdocs.py R5DIR: assembles the deliverables in R5DIR from R5DIR/out (made by the other tools; no ROM access):
TEXT_<game>.tsv, UNREACHABLE_<game>.tsv, UNUSED_<game>.tsv (copies), DEBUG_<game>.md (tools/debug_notes_<game>.md +
the generated function table) and GAME_DIFF.md (from out/diff_functions.tsv, diff_data.tsv, diff_text.tsv)."""
import sys, os, csv, shutil
from collections import Counter

r5 = sys.argv[1]
out = os.path.join(r5, 'out')
for g in ('letter', 'number'):
    for k in ('UNREACHABLE', 'UNUSED'):
        shutil.copyfile(os.path.join(out, '%s_%s.tsv' % (k, g)), os.path.join(r5, '%s_%s.tsv' % (k, g)))
    import json, re
    gr = json.load(open(os.path.join(out, 'graph_%s.json' % g)))
    with open(os.path.join(r5, 'TEXT_%s.tsv' % g), 'w') as o:
        for i, line in enumerate(open(os.path.join(out, 'TEXT_%s.tsv' % g))):
            line = line.rstrip('\n')
            if i == 0:
                o.write(line + '\treferencing_code_reachable\n'); continue
            ref = line.split('\t')[7]
            fns = [f for f in re.findall(r'func_([0-9A-F]{8})', ref) if '(+' not in ref.split('func_' + f)[1][:3]]
            st = '-' if not fns else ('yes' if any(gr.get(f, {}).get('reach_any') for f in fns) else 'NO (only unreachable code)')
            o.write(line + '\t' + st + '\n')
    notes = open(os.path.join(r5, 'tools', 'debug_notes_%s.md' % g)).read()
    rows = list(csv.DictReader(open(os.path.join(out, 'debug_%s.tsv' % g)), delimiter='\t'))
    t = ['', '## Every debug / development function (generated by tools/debug.py)', '',
         'category: rmon / rdb (libultra debugger, by address range mapped through twin hashes), print (print paths), hook, '
         'profiler, overlay, error (hand-identified seeds); calls-print = calls a print path directly; uses-debug-string = '
         'builds the address of a debug/error string. callers: functions (or `tbl@` data words) that reference it.', '',
         '| func | library | category | role | reachable | callers | debug strings used |', '|---|---|---|---|---|---|---|']
    for r in rows:
        t.append('| %s | %s | %s | %s | %s | %s | %s |' % (r['func'], r['library'], r['category'], r['role'], r['reach_from_entry'],
                 r['callers'].replace(',', ', ')[:200], r['debug_strings_used'].replace('|', '/')[:200]))
    open(os.path.join(r5, 'DEBUG_%s.md' % g), 'w').write(notes.rstrip() + '\n' + '\n'.join(t) + '\n')

fr = list(csv.DictReader(open(os.path.join(out, 'diff_functions.tsv')), delimiter='\t'))
dr = list(csv.DictReader(open(os.path.join(out, 'diff_data.tsv')), delimiter='\t'))
tr = list(csv.DictReader(open(os.path.join(out, 'diff_text.tsv')), delimiter='\t'))
L = [r for r in fr if r['game'] == 'letter']; N = [r for r in fr if r['game'] == 'number']
md = ['# Differences between the two programs (Letter Adventure vs Number Journey)', '',
      'Generated by `tools/gamediff.py` and `tools/textdiff.py` (run through `tools/run.sh diff`), then `tools/mkdocs.py`.', '',
      '## Functions', '',
      'Twins = functions whose hash (sestools/functions.json) occurs exactly once in each game: %d pairs (a few more functions are identical stubs that occur several times). ' % int(open(os.path.join(out, 'diff_summary.txt')).read()) +
      'Letter-only: %d functions, %d bytes; Number-only: %d functions, %d bytes. ' % (len(L), sum(int(r['size']) for r in L), len(N), sum(int(r['size']) for r in N)) +
      'By library: ' + ', '.join('%s %s %d' % (k[0], k[1], v) for k, v in sorted(Counter((r['game'], r['library']) for r in fr).items())) + '. '
      'Every libultra, libmus, libm/libc and GSM function exists in both games with the same hash, except the boot entry '
      '(func_80000400: it embeds the game-specific BSS bounds) and one hand-written libultra routine (the exception handler, '
      'Letter func_80060544 / Number func_80061EB4: same code, different absolute addresses inside it). '
      'The game-only functions are grouped below by the twin function that precedes them (segment column), so a function '
      'rewritten for one game sits next to its counterpart; the largest single block is the one after the twin anchor L800362F0 / N800380E8 (%s): each game\'s own level, item and bonus-game logic.' % ', '.join('%s %d functions / %d bytes' % (g, sum(1 for r in fr if r['game'] == g and r['segment(after twin anchor L/N)'] == 'L800362F0/N800380E8'), sum(int(r['size']) for r in fr if r['game'] == g and r['segment(after twin anchor L/N)'] == 'L800362F0/N800380E8')) for g in ('letter', 'number')), '',
      '| after twin anchor (Letter/Number) | game | function | library | size | reachable | description |', '|---|---|---|---|---|---|---|']
for r in fr:
    md.append('| %s | %s | %s | %s | %s | %s | %s |' % (r['segment(after twin anchor L/N)'], r['game'], r['func'], r['library'], r['size'], r['reachable'], r['description'][:140]))
paired = [r for r in dr if not r['comparison'].startswith('no twin')]
c = Counter(r['comparison'].split(' (')[0] for r in paired)
md += ['', '## Data tables', '',
       'Objects (extents from agents data1/data2) paired through twin functions: the i-th address built by a Letter twin '
       'and the i-th built by its Number copy name the same object. %d pairs: %s. ' % (len(paired), ', '.join('%s %d' % kv for kv in sorted(c.items()))) +
       '"pointers only" = every differing 32-bit word is a RAM pointer in both games (relocated tables, same content). '
       'Objects used only by game-only functions cannot be paired this way: Letter %d, Number %d objects (listed in out/diff_data.tsv).' % (
           sum(1 for r in dr if r['comparison'].startswith('no twin') and r['letter_ram'] != '-'), sum(1 for r in dr if r['comparison'].startswith('no twin') and r['letter_ram'] == '-')), '',
       '| Letter object | size | class | Number object | size | comparison |', '|---|---|---|---|---|---|']
for r in paired:
    if r['comparison'] != 'identical':
        md.append('| %s %s | %s | %s | %s | %s | %s |' % (r['letter_ram'], r['letter_object'][:50], r['letter_size'], r['class'], r['number_ram'], r['number_size'], r['comparison']))
md += ['', '## Text', '', 'Program strings present in one game only, and staff-credit lines that differ (from TEXT_<game>.tsv).', '',
       '| kind | address(es) | text | referenced by |', '|---|---|---|---|']
for r in tr:
    md.append('| %s | %s | `%s` | %s |' % (r['kind'], r['ram'], r['text'].replace('|', '/'), r['referenced_by']))
md += ['', '## Outside the program', '',
       'Header, IPL3 and all RSP microcode sections are identical apart from the name, game id and CRCs (agent ucode). '
       'The asset files differ entirely (different levels, songs, speech); see FILES_<game>.tsv.']
open(os.path.join(r5, 'GAME_DIFF.md'), 'w').write('\n'.join(md) + '\n')
print('docs written')
