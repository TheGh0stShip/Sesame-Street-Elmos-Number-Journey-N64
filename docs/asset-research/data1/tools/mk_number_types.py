rows = []
for ln in open(letter):
    if ln.startswith('#') or not ln.strip():
        continue
    f = ln.rstrip('\n').split('\t')
    a = int(f[0], 16)
    if a < 0x8006C9AC:
        continue  # the entry island is auto pad in both games
    if a < 0x8006DDF0:
        d = 0x1970
    elif a >= 0x8006EDE8:
        d = 0x1080
    else:
        continue  # letter HUD block: replaced by NUMBER_HUD
    f[0] = '%08X' % (a + d)
    f[3] = f[3].replace('%08X' % a, '%08X' % (a + d))
    f[2] = f[2].replace('struct TexPair{word tlut;word img}', 'TexPair')
    f[6] = 'letter twin D_%08X (%s)' % (a, f[6])
    rows.append(f)
for ln in NUMBER_HUD.strip('\n').split('\n'):
    rows.append(ln.split('\t'))
rows.sort(key=lambda f: int(f[0], 16))
# the first row that uses TexPair must define it
seen = False
for f in rows:
    if 'TexPair' in f[2] and not seen:
        f[2] = f[2].replace('TexPair', 'struct TexPair{word tlut;word img}', 1) if 'struct TexPair' not in f[2] else f[2]
        seen = True
with open(out, 'w') as o:
    o.write('# GENERATED by mk_number_types.py from types_letter.tsv + the hand-written HUD block; no data values\n')
    o.write('# ram\tsize\tctype\tname\tclass\tcomment\tevidence\n')
    for f in rows:
        a = int(f[0], 16)
        nr = '; '.join(sorted(R.get(a, ())))[:300]
        f[6] = f[6] + (' | number refs: ' + nr if nr else ' | no direct number ref')
        o.write('\t'.join(f) + '\n')
print(len(rows), 'rows')
